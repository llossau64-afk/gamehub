# Generates Scripts/Core/MatDefs.Models.cs and Scripts/Core/ArtIndex.cs from the conversion data.
import json, re, os
D = '/home/user/gamehub/Downfall/Assets/Downfall/Scripts/Core'
info = json.load(open('matinfo.json')); rep = json.load(open('models_report.json')); cars = json.load(open('cars_info.json'))
def srgb(v): return 12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055
def col(c): return 'new Color(%.4ff, %.4ff, %.4ff, %.4ff)' % (srgb(c[0]), srgb(c[1]), srgb(c[2]), c[3] if len(c) > 3 else 1)
def san(n): return re.sub(r'[^A-Za-z0-9_]+', '_', n)
def kind(n):
    if 'needles' in n: return 'needle'
    if 'leaves' in n: return 'leaf'
    if re.search('grass|fern', n): return 'grass'
    return None
lines = []
for glb, d in info.items():
    for m in d['materials']:
        n = m['name']; t = m['tex']
        s = 'l.Add(new MatDef("Models/%s", %s, %.3ff, %.3ff)' % (san(n), col(m['baseColor']), m['roughness'], m['metallic'])
        if 'base' in t: s += '.Tex("%s/%s")' % (glb, t['base'])
        if 'normal' in t: s += '.Normal("%s/%s")' % (glb, t['normal'])
        if 'mr' in t: s += '.MetalMap("%s/%s_ms")' % (glb, t['mr'])
        e = m['emissive'] or [0, 0, 0]
        if max(e) > 0:
            s += '.Emit(%s, %.3ff%s)' % (col(e), m['emissiveStrength'], (', "%s/%s"' % (glb, t['emissive'])) if 'emissive' in t else '')
        k = kind(n)
        if k: s += '.Cut(0.45f).TwoSided()'
        elif n.startswith('b_') and re.search('railing|flowers', n): s += '.Cut(0.5f)'
        elif m['transmission'] > 0: s += '.Transparent(0.25f).NoShadows()'
        elif m['alphaMode'] == 'BLEND': s += '.Transparent(%.3ff).NoShadows()' % (m['baseColor'][3] if len(m['baseColor']) > 3 else 1)
        elif m['alphaMode'] == 'MASK': s += '.Cut(%.3ff)' % m['alphaCutoff']
        if m['doubleSided'] and not k: s += '.TwoSided()'
        s += '.From("%s.glb material %s"));' % (glb, n)
        lines.append(s)
carl = []
for c in cars:
    sport = c['sport']
    rough, metal = (0.3, 0.55) if sport else (0.42, 0.05)
    carl.append('l.Add(MatDef_("car_paint_%s", 0x%06x, %.2ff, %.2ff).From("makePaint(model.paint, %s)"));' % (c['id'], c['paint'], rough, metal, 'metallic' if sport else 'solid'))
    carl.append('l.Add(MatDef_("car_trim_%s", 0x%06x, 0.7f, 0.1f).From("trimMat (model.trim)"));' % (c['id'], c['trim']))
    carl.append('l.Add(MatDef_("car_plate_%s", 0xffffff, 0.6f, 0f).Tex("Generated/plate_%s").NoShadows().From("plateTexture(plateText(id))"));' % (c['id'], c['id']))
out = '''// <auto-generated> by the asset conversion (gen_cs.py): GLB materials and per-car materials. Do not edit.
using System.Collections.Generic;
using UnityEngine;

namespace Downfall
{
    public static partial class MatDefs
    {
        static MatDef MatDef_(string n, int hex, float rough, float metal) => new MatDef(n, MatDef.Hex(hex), rough, metal);

        static partial void AddModels(List<MatDef> l)
        {
            // Blender GLB materials (Resources/Materials/Models/<name>)
%s
            // per car: paint, trim (bumper on non-chrome, non-sport cars), number plate
%s
        }
    }
}
''' % ('\n'.join('            ' + x for x in lines), '\n'.join('            ' + x for x in carl))
open(f'{D}/MatDefs.Models.cs', 'w').write(out)

ents = []
for x in rep:
    base = os.path.splitext(os.path.basename(x['file']))[0]
    key = x['name']
    ents.append('            { "%s", "Prefabs/%s/%s" },' % (key, x['category'], base))
carinfo = '\n'.join('            new CarArt("%s", %s, %s, %s, %.2ff, "%s"),' % (c['id'], str(c['chrome']).lower(),
           str(bool(c['sport'] or c['type'] in ('super', 'hyper', 'sports'))).lower(), str(c['sport']).lower(), c['wear'], c['rim']) for c in cars)
cats = {}
for x in rep: cats.setdefault(x['category'], []).append(x['name'])
catl = '\n'.join('            { "%s", new[] { %s } },' % (k, ', '.join('"%s"' % n for n in v)) for k, v in cats.items())
out2 = '''// <auto-generated> by the asset conversion (gen_cs.py) from the GLB contents. Do not edit.
// JS asset name -> Resources path of the generated prefab (see Art/MANIFEST.md).
using System.Collections.Generic;

namespace Downfall
{
    public sealed class CarArt
    {
        public readonly string id, rim;
        public readonly bool chrome, sportBody, sport;
        public readonly float wear;
        public CarArt(string id, bool chrome, bool sportBody, bool sport, float wear, string rim)
        { this.id = id; this.chrome = chrome; this.sportBody = sportBody; this.sport = sport; this.wear = wear; this.rim = rim; }
    }

    public static class ArtIndex
    {
        /// <summary>JS name (assetParts/cloneAsset/carAsset id, "fox") -> Resources path.</summary>
        public static readonly Dictionary<string, string> Prefabs = new Dictionary<string, string>
        {
%s
        };

        /// <summary>Category folder -> JS names in it (Cars holds car ids).</summary>
        public static readonly Dictionary<string, string[]> ByCategory = new Dictionary<string, string[]>
        {
%s
        };

        /// <summary>Per-car flags that decide which material a GLB part gets (carModel.js buildAssetBody).</summary>
        public static readonly CarArt[] Cars =
        {
%s
        };

        public static string PrefabPath(string jsName) => jsName != null && Prefabs.TryGetValue(jsName, out var p) ? p : null;

        public static CarArt Car(string id) { foreach (var c in Cars) if (c.id == id) return c; return null; }

        /// <summary>carModel.js buildAssetBody() matFor(kind, part): GLB material kind ("paint", "bumper" … the
        /// GLB material name without "car_") -> Mats name. Paint/trim/plate are per car.</summary>
        public static string CarPartMaterial(string carId, string kind, string part)
        {
            var c = Car(carId);
            switch (kind)
            {
                case "paint": return c != null && c.wear > 0.5f && part == "fenderFR" ? "car_odd" : "car_paint_" + carId;
                case "bumper": return c != null && c.chrome ? "chrome" : c != null && c.sportBody ? "car_paint_" + carId : "car_trim_" + carId;
                case "trim": return "car_trim";
                case "chrome": case "mirror": return "chrome";
                case "glass": return "glass";
                case "headlight": return "headlight";
                case "taillight": return "taillight";
                case "amber": return "car_amber";
                case "grille": return "car_grille";
                case "plate": return "car_plate_" + carId;
                case "under": case "wells": return "car_under";
                case "dash": return "car_dash";
                case "cabin": return "car_cabin";
                case "seat": return "car_seat";
                case "gauges": return "car_gauges";
                default: return "car_paint_" + carId;
            }
        }

        /// <summary>Car parts that do not cast shadows in the JS (buildAssetBody noShadow set).</summary>
        public static readonly HashSet<string> CarNoShadow = new HashSet<string>
        { "glass", "lightL", "lightR", "tail", "amber", "plateF", "plateR", "gauges", "seals", "mirrorGlass", "grille", "under", "cabin" };
    }
}
''' % ('\n'.join(ents), catl, carinfo)
open(f'{D}/ArtIndex.cs', 'w').write(out2)
print(len(lines), len(carl), len(ents))
